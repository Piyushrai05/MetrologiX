    instrument_id: str = Field(..., min_length=1)
    test_type: str = Field("type_evaluation", description="type_evaluation or verification")
    inspector_name: str = Field(..., min_length=1, description="Lead inspector full name")
    lab_location: str = Field(..., min_length=1, description="Laboratory name and location")
    ambient_temp_c: float = Field(20.0, description="Ambient temperature in °C")
    relative_humidity: float = Field(50.0, ge=0, le=100, description="Relative humidity (0–100 %RH)")
    pressure_hpa: float = Field(1013.0, gt=0, description="Atmospheric pressure in hPa")

    @field_validator("test_type")
    @classmethod
    def validate_test_type(cls, v: str) -> str:
        allowed = {"type_evaluation", "verification"}
        if v not in allowed:
            raise ValueError(f"test_type must be one of {sorted(allowed)}, got '{v}'")
        return v


"""
Pydantic request/response models with full field-level validation.
Validation errors are returned as structured JSON with field names
so the UI can display them next to the relevant input.
"""
from __future__ import annotations

from pydantic import BaseModel, Field, field_validator, model_validator
from typing import Any, Dict, List, Optional


# ---------------------------------------------------------------------------
# Accepted accuracy classes
# ---------------------------------------------------------------------------
_ACCEPTED_CLASSES = {"I", "II", "III", "IIII", "IV"}


# ---------------------------------------------------------------------------
# Instrument
# ---------------------------------------------------------------------------

class InstrumentCreate(BaseModel):
    model_number: str = Field(..., min_length=1, description="Instrument model identifier")
    manufacturer: str = Field(..., min_length=1, description="Manufacturer name")
    serial_number: str = Field(..., min_length=1, description="Instrument serial number")
    accuracy_class: str = Field(..., description="OIML accuracy class: I, II, III, or IIII")
    max_capacity: float = Field(..., gt=0, description="Maximum weighing capacity (must be > 0)")
    min_capacity: float = Field(..., ge=0, description="Minimum weighing capacity (must be ≥ 0)")
    scale_interval_e: float = Field(..., gt=0, description="Verification scale interval e (must be > 0)")
    scale_interval_d: float = Field(..., gt=0, description="Actual scale interval d (must be > 0)")
    unit: str = Field("kg", description="Measurement unit (kg, g, lb, t)")

    @field_validator("accuracy_class")
    @classmethod
    def validate_accuracy_class(cls, v: str) -> str:
        if v not in _ACCEPTED_CLASSES:
            raise ValueError(
                f"accuracy_class must be one of {sorted(_ACCEPTED_CLASSES)}, got '{v}'"
            )
        return v

    @field_validator("unit")
    @classmethod
    def validate_unit(cls, v: str) -> str:
        allowed = {"kg", "g", "lb", "t", "N"}
        if v not in allowed:
            raise ValueError(f"unit must be one of {sorted(allowed)}, got '{v}'")
        return v

    @model_validator(mode="after")
    def validate_capacity_ordering(self) -> "InstrumentCreate":
        errors: List[str] = []
        if self.max_capacity <= self.min_capacity:
            errors.append("max_capacity must be strictly greater than min_capacity")
        # d ≤ e  (R76-1 §3.2 — verified:false, see oiml_config.json)
        if self.scale_interval_d > self.scale_interval_e:
            errors.append(
                f"scale_interval_d ({self.scale_interval_d}) must be ≤ "
                f"scale_interval_e ({self.scale_interval_e})  [R76-1 §3.2 — unverified]"
            )
        if errors:
            raise ValueError("; ".join(errors))
        return self


